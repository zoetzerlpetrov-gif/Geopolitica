import { chromium } from "playwright";
const URL_SITIO = "https://zoetzerlpetrov-gif.github.io/Geopolitica/";
const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-unsafe-swiftshader"] });
const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
p.on("console", (m) => { if (["error", "warning"].includes(m.type())) console.log("CONSOLA", m.type(), m.text().slice(0, 300)); });
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
p.on("requestfailed", (r) => console.log("FALLO", r.url().slice(0, 150), r.failure()?.errorText));
p.on("response", (r) => { if (/camaras|grupos/.test(r.url())) console.log("RESP", r.status(), r.url().slice(0, 150)); });
await p.goto(URL_SITIO, { waitUntil: "load" });
await p.waitForTimeout(15000);
const info = await p.evaluate(() => {
  const cb = document.querySelector('[data-fam="camaras"]');
  return { existe: !!cb, disabled: cb?.disabled, padre: cb?.closest("[id]")?.id, camCapas: document.getElementById("cam-capas")?.innerHTML.slice(0, 600) };
});
console.log("INFO", JSON.stringify(info));
await p.evaluate(() => { const cb = document.querySelector('[data-fam="camaras"]'); for (let d = cb?.parentElement; d; d = d.parentElement) if (d.tagName === "DETAILS") d.open = true; cb?.scrollIntoView(); });
await p.waitForTimeout(500);
await p.screenshot({ path: "capturas/01-menu.png" });
await p.click('[data-fam="camaras"]', { force: true }).catch((e) => console.log("CLIC", e.message));
await p.waitForTimeout(25000);
await p.screenshot({ path: "capturas/02-encendida.png" });
const est = await p.evaluate(() => [...document.querySelectorAll("[data-fam-sub=camaras]")].map((x) => `${x.value}:${x.checked}`).join(","));
console.log("SUBS", est);
await b.close();
